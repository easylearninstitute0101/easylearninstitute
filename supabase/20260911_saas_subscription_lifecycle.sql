-- Easylearn Institute Progress 15
-- SaaS plans, institute subscriptions, manual payment approval and platform audit log.

create table if not exists public.subscription_plans (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  monthly_price numeric(12,2) not null default 0,
  yearly_price numeric(12,2) not null default 0,
  max_students integer,
  max_teachers integer,
  features jsonb not null default '{}'::jsonb,
  status text not null default 'active' check (status in ('active','inactive')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.subscriptions (
  id uuid primary key default gen_random_uuid(),
  institute_id uuid not null references public.institutes(id) on delete cascade,
  plan_id uuid not null references public.subscription_plans(id),
  status text not null default 'trial' check (status in ('trial','active','past_due','suspended','cancelled','expired')),
  billing_cycle text not null default 'monthly' check (billing_cycle in ('monthly','yearly')),
  starts_at timestamptz not null default now(),
  trial_ends_at timestamptz,
  current_period_start timestamptz,
  current_period_end timestamptz,
  cancelled_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists uq_subscriptions_one_live_per_institute
on public.subscriptions(institute_id)
where status in ('trial','active','past_due');
create index if not exists idx_subscriptions_institute on public.subscriptions(institute_id);

create table if not exists public.subscription_payments (
  id uuid primary key default gen_random_uuid(),
  institute_id uuid not null references public.institutes(id) on delete cascade,
  subscription_id uuid not null references public.subscriptions(id) on delete cascade,
  requested_plan_id uuid references public.subscription_plans(id) on delete set null,
  amount numeric(12,2) not null check (amount > 0),
  method text not null check (method in ('Cash','bKash','Nagad','Rocket','Bank')),
  transaction_reference text,
  payment_date date not null default current_date,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  note text,
  created_at timestamptz not null default now()
);
alter table public.subscription_payments add column if not exists requested_plan_id uuid references public.subscription_plans(id) on delete set null;

create index if not exists idx_subscription_payments_institute on public.subscription_payments(institute_id, payment_date desc);

create table if not exists public.platform_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  institute_id uuid references public.institutes(id) on delete set null,
  actor_user_id uuid references auth.users(id) on delete set null,
  action text not null,
  entity_type text,
  entity_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists idx_audit_logs_institute_created on public.audit_logs(institute_id, created_at desc);

